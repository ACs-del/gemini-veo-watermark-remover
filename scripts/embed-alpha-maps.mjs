/**
 * Build-time script: decode calibrated PNG captures from GeminiWatermarkTool /
 * VeoWatermarkRemover and emit embedded alpha map modules for browser + Node.
 *
 * Alpha extraction mirrors upstream calculate_alpha_map():
 *   alpha = max(R, G, B) / 255
 */

import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const masksDir = join(root, 'assets', 'masks')
const require = createRequire(import.meta.url)

let sharp
try {
  sharp = (await import('sharp')).default
} catch {
  console.error('embed-alpha-maps: install sharp (npm install) before building.')
  process.exit(1)
}

/** @typedef {{ width: number, height: number, alpha: Float32Array }} AlphaMap */

/**
 * Decode PNG file to alpha map (max RGB channel, normalized 0–1).
 * @param {string} filePath
 * @returns {Promise<AlphaMap>}
 */
async function pngToAlphaMap(filePath) {
  const { data, info } = await sharp(filePath)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true })

  const { width, height, channels } = info
  const alpha = new Float32Array(width * height)

  for (let i = 0; i < width * height; i++) {
    const base = i * channels
    const r = data[base]
    const g = data[base + 1]
    const b = data[base + 2]
    alpha[i] = Math.max(r, g, b) / 255
  }

  return { width, height, alpha }
}

/**
 * Bilinear resize of alpha map (matches embeddedAlphaMaps.resizeAlphaMap).
 */
function resizeAlphaMap(source, sourceWidth, sourceHeight, targetWidth, targetHeight) {
  if (sourceWidth === targetWidth && sourceHeight === targetHeight) {
    return new Float32Array(source)
  }

  const result = new Float32Array(targetWidth * targetHeight)
  const xScale = sourceWidth / targetWidth
  const yScale = sourceHeight / targetHeight

  for (let y = 0; y < targetHeight; y++) {
    const sourceY = (y + 0.5) * yScale - 0.5
    const sourceY0 = Math.floor(sourceY)
    const y0 = Math.max(0, sourceY0)
    const y1 = Math.min(sourceHeight - 1, y0 + 1)
    const yWeight = Math.max(0, Math.min(1, sourceY - sourceY0))

    for (let x = 0; x < targetWidth; x++) {
      const sourceX = (x + 0.5) * xScale - 0.5
      const sourceX0 = Math.floor(sourceX)
      const x0 = Math.max(0, sourceX0)
      const x1 = Math.min(sourceWidth - 1, x0 + 1)
      const xWeight = Math.max(0, Math.min(1, sourceX - sourceX0))

      const top =
        source[y0 * sourceWidth + x0] * (1 - xWeight) +
        source[y0 * sourceWidth + x1] * xWeight
      const bottom =
        source[y1 * sourceWidth + x0] * (1 - xWeight) +
        source[y1 * sourceWidth + x1] * xWeight

      result[y * targetWidth + x] = top * (1 - yWeight) + bottom * yWeight
    }
  }

  return result
}

/** Pack Float32 alpha values as base64 uint8 (alpha * 255). */
function packAlphaBase64(alpha) {
  const bytes = new Uint8Array(alpha.length)
  for (let i = 0; i < alpha.length; i++) {
    bytes[i] = Math.round(Math.max(0, Math.min(1, alpha[i])) * 255)
  }
  return Buffer.from(bytes).toString('base64')
}

/**
 * @param {Record<string, { width: number, height: number, alpha: Float32Array, source: string }>} entries
 */
function emitCalibratedModule(entries) {
  const lines = [
    '/**',
    ' * Auto-generated by scripts/embed-alpha-maps.mjs — do not edit manually.',
    ' * Sources: GeminiWatermarkTool v0.3.1 embedded_assets.hpp +',
    ' *          VeoWatermarkRemover v0.5.0-demo binary (legacy Veo text captures).',
    ' */',
    '',
    '/** @typedef {{ width: number, height: number, source: string, dataBase64: string }} CalibratedAlphaEntry */',
    '',
    '/** @type {Record<string, CalibratedAlphaEntry>} */',
    'export const CALIBRATED_ALPHA_ENTRIES = {',
  ]

  for (const [key, { width, height, alpha, source }] of Object.entries(entries)) {
    const b64 = packAlphaBase64(alpha)
    lines.push(`  '${key}': { width: ${width}, height: ${height}, source: '${source}', dataBase64: '${b64}' },`)
  }

  lines.push('}', '')
  lines.push(`
/** Decode a packed alpha entry into Float32Array (0–1). */
export function decodeCalibratedAlpha(entry) {
  const binary = typeof atob === 'function'
    ? atob(entry.dataBase64)
    : Buffer.from(entry.dataBase64, 'base64').toString('binary')

  const map = new Float32Array(entry.width * entry.height)
  for (let i = 0; i < map.length; i++) {
    map[i] = binary.charCodeAt(i) / 255
  }
  return map
}

/** @returns {{ data: Float32Array, width: number, height: number, source: string }|null} */
export function loadCalibratedAlphaMap(key) {
  const entry = CALIBRATED_ALPHA_ENTRIES[key]
  if (!entry) return null
  return {
    data: decodeCalibratedAlpha(entry),
    width: entry.width,
    height: entry.height,
    source: entry.source,
  }
}
`)

  return lines.join('\n')
}

/** Generate standalone browser snippet for extension / userscript. */
function emitBrowserAlphaSnippet(entries) {
  const geminiKeys = ['gemini-v2-36', 'gemini-v2-96', 'gemini-48', 'gemini-96']
  const lines = [
    '// Auto-generated by scripts/embed-alpha-maps.mjs',
    'function gvwrDecodeAlpha(entry) {',
    '  const binary = atob(entry.dataBase64);',
    '  const map = new Float32Array(entry.width * entry.height);',
    '  for (let i = 0; i < map.length; i++) map[i] = binary.charCodeAt(i) / 255;',
    '  return map;',
    '}',
    'const GVWR_ALPHA_ENTRIES = {',
  ]

  for (const key of geminiKeys) {
    const e = entries[key]
    lines.push(`  '${key}': { width: ${e.width}, height: ${e.height}, dataBase64: '${packAlphaBase64(e.alpha)}' },`)
  }

  lines.push('};')
  lines.push('const GVWR_ALPHA_MAPS = {')
  lines.push("  'gemini-v2-36': { width: 36, height: 36, data: gvwrDecodeAlpha(GVWR_ALPHA_ENTRIES['gemini-v2-36']) },")
  lines.push("  'gemini-v2-96': { width: 96, height: 96, data: gvwrDecodeAlpha(GVWR_ALPHA_ENTRIES['gemini-v2-96']) },")
  lines.push("  'gemini-48': { width: 48, height: 48, data: gvwrDecodeAlpha(GVWR_ALPHA_ENTRIES['gemini-48']) },")
  lines.push("  'gemini-96': { width: 96, height: 96, data: gvwrDecodeAlpha(GVWR_ALPHA_ENTRIES['gemini-96']) },")
  lines.push('};')

  return lines.join('\n')
}

const GVWR_BEGIN = '// @GVWR_ALPHA_MAPS_BEGIN'
const GVWR_END = '// @GVWR_ALPHA_MAPS_END'

async function patchBrowserClient(filePath, snippet) {
  let content = await readFile(filePath, 'utf8')
  const start = content.indexOf(GVWR_BEGIN)
  const end = content.indexOf(GVWR_END)
  if (start === -1 || end === -1) {
    throw new Error(`Missing alpha map markers in ${filePath}`)
  }
  const before = content.slice(0, start + GVWR_BEGIN.length)
  const after = content.slice(end)
  content = `${before}\n${snippet}\n${after}`
  await writeFile(filePath, content)
}

async function generateExtensionIcons() {
  const iconsDir = join(root, 'src', 'extension', 'icons')
  await mkdir(iconsDir, { recursive: true })

  for (const size of [16, 48, 128]) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
      <defs>
        <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
          <stop offset="0%" stop-color="#6366f1"/>
          <stop offset="100%" stop-color="#8b5cf6"/>
        </linearGradient>
      </defs>
      <rect width="${size}" height="${size}" rx="${Math.round(size * 0.22)}" fill="url(#g)"/>
      <path fill="#fff" opacity="0.95" d="M${size * 0.5} ${size * 0.18} L${size * 0.62} ${size * 0.38} L${size * 0.82} ${size * 0.5} L${size * 0.62} ${size * 0.62} L${size * 0.5} ${size * 0.82} L${size * 0.38} ${size * 0.62} L${size * 0.18} ${size * 0.5} L${size * 0.38} ${size * 0.38} Z"/>
    </svg>`

    await sharp(Buffer.from(svg)).png().toFile(join(iconsDir, `icon${size}.png`))
  }
}

async function main() {
  const geminiV1Small = await pngToAlphaMap(join(masksDir, 'bg_48.png'))
  const geminiV1Large = await pngToAlphaMap(join(masksDir, 'bg_96.png'))
  const geminiV2Small = await pngToAlphaMap(join(masksDir, 'bg_b_36.png'))
  const geminiV2Large = await pngToAlphaMap(join(masksDir, 'bg_b_96.png'))

  const veo720Capture = await pngToAlphaMap(join(masksDir, 'veo_legacy_68x30.png'))
  const veo1080Capture = await pngToAlphaMap(join(masksDir, 'veo_legacy_99x43.png'))

  const veo720Alpha = resizeAlphaMap(
    veo720Capture.alpha,
    veo720Capture.width,
    veo720Capture.height,
    80,
    28,
  )
  const veo1080Alpha = resizeAlphaMap(
    veo1080Capture.alpha,
    veo1080Capture.width,
    veo1080Capture.height,
    120,
    42,
  )

  /** @type {Record<string, { width: number, height: number, alpha: Float32Array, source: string }>} */
  const entries = {
    'gemini-v2-36': { ...geminiV2Small, alpha: geminiV2Small.alpha, source: 'GeminiWatermarkTool/bg_b_36' },
    'gemini-v2-96': { ...geminiV2Large, alpha: geminiV2Large.alpha, source: 'GeminiWatermarkTool/bg_b_96' },
    'gemini-48': { ...geminiV1Small, alpha: geminiV1Small.alpha, source: 'GeminiWatermarkTool/bg_48' },
    'gemini-96': { ...geminiV1Large, alpha: geminiV1Large.alpha, source: 'GeminiWatermarkTool/bg_96' },
    '720p-landscape': { width: 80, height: 28, alpha: veo720Alpha, source: 'VeoWatermarkRemover/720p-text' },
    '720p-portrait': { width: 80, height: 28, alpha: veo720Alpha, source: 'VeoWatermarkRemover/720p-text' },
    '1080p-landscape': { width: 120, height: 42, alpha: veo1080Alpha, source: 'VeoWatermarkRemover/1080p-text' },
    '1080p-portrait': { width: 120, height: 42, alpha: veo1080Alpha, source: 'VeoWatermarkRemover/1080p-text' },
    'veo-diamond-1080p-landscape': { width: 96, height: 96, alpha: geminiV2Large.alpha, source: 'GeminiWatermarkTool/bg_b_96' },
    'veo-diamond-1080p-portrait': { width: 96, height: 96, alpha: geminiV2Large.alpha, source: 'GeminiWatermarkTool/bg_b_96' },
  }

  const coreDir = join(root, 'src', 'core')
  await writeFile(join(coreDir, 'calibratedAlphaData.js'), emitCalibratedModule(entries))

  const sharedDir = join(root, 'src', 'shared')
  await mkdir(sharedDir, { recursive: true })
  const snippet = emitBrowserAlphaSnippet(entries)
  await writeFile(join(sharedDir, 'browserAlphaMaps.snippet.js'), snippet)

  const extensionContent = join(root, 'src', 'extension', 'content.js')
  const userscriptPath = join(root, 'src', 'userscript', 'gemini-veo-watermark-remover.user.js')
  await patchBrowserClient(extensionContent, snippet)
  await patchBrowserClient(userscriptPath, snippet)

  await generateExtensionIcons()

  // Public mask PNGs for removegeminiwatermark static hosting
  const publicDir = join(root, '..', 'nextjs-saas-monorepo', 'apps', 'removegeminiwatermark', 'public')
  const publicMasks = join(publicDir, 'masks')
  const publicUserscript = join(publicDir, 'userscript')
  await mkdir(publicMasks, { recursive: true })
  await mkdir(publicUserscript, { recursive: true })
  await copyFile(join(masksDir, 'bg_48.png'), join(publicMasks, 'gemini-alpha-48.png'))
  await copyFile(join(masksDir, 'bg_96.png'), join(publicMasks, 'gemini-alpha-96.png'))
  await copyFile(join(masksDir, 'bg_b_36.png'), join(publicMasks, 'gemini-alpha-36.png'))
  await copyFile(join(masksDir, 'bg_b_96.png'), join(publicMasks, 'gemini-alpha-96-v2.png'))
  await copyFile(userscriptPath, join(publicUserscript, 'gemini-veo-watermark-remover.user.js'))

  console.log(`Embedded ${Object.keys(entries).length} calibrated alpha maps.`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
